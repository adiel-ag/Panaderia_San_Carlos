CREATE TABLE MOVIMIENTO_INVENTARIO (
    id_movimiento NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_producto NUMBER NOT NULL,
    id_usuario NUMBER,
    tipo_movimiento VARCHAR2(20) NOT NULL,
    cantidad NUMBER(14,3) NOT NULL,
    origen VARCHAR2(20) NOT NULL,
    id_referencia NUMBER,
    fecha_movimiento TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    observacion VARCHAR2(500),

    CONSTRAINT pk_mov_inventario
        PRIMARY KEY (id_movimiento),

    CONSTRAINT fk_mov_inv_producto
        FOREIGN KEY (id_producto)
        REFERENCES PRODUCTO(id_producto),

    CONSTRAINT fk_mov_inv_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES USUARIO(id_usuario),

    CONSTRAINT ck_mov_inv_tipo
        CHECK (
            tipo_movimiento IN (
                'ENTRADA',
                'SALIDA',
                'AJUSTE_POS',
                'AJUSTE_NEG'
            )
        ),

    CONSTRAINT ck_mov_inv_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT ck_mov_inv_origen
        CHECK (
            origen IN (
                'INICIAL',
                'PRODUCCION',
                'DESPACHO',
                'AJUSTE',
                'OTRO'
            )
        )
);
