CREATE TABLE PRODUCTO (
    id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_tipo_producto NUMBER NOT NULL,
    id_unidad NUMBER NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    stock_minimo NUMBER(12,3) DEFAULT 0 NOT NULL,
    estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_producto
        PRIMARY KEY (id_producto),

    CONSTRAINT fk_producto_tipo
        FOREIGN KEY (id_tipo_producto)
        REFERENCES TIPO_PRODUCTO(id_tipo_producto),

    CONSTRAINT fk_producto_unidad
        FOREIGN KEY (id_unidad)
        REFERENCES UNIDAD_MEDIDA(id_unidad),

    CONSTRAINT uq_producto_nombre
        UNIQUE (nombre),

    CONSTRAINT ck_producto_stock_min
        CHECK (stock_minimo >= 0),

    CONSTRAINT ck_producto_estado
        CHECK (estado IN ('ACTIVO','INACTIVO'))
);



