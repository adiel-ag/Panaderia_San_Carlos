CREATE TABLE PRODUCCION (
    id_produccion NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario NUMBER NOT NULL,
    fecha_produccion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    estado VARCHAR2(20) DEFAULT 'PLANIFICADA' NOT NULL,
    observacion VARCHAR2(500),

    CONSTRAINT pk_produccion
        PRIMARY KEY (id_produccion),

    CONSTRAINT fk_produccion_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES USUARIO(id_usuario),

    CONSTRAINT ck_produccion_estado
        CHECK (
            estado IN (
                'PLANIFICADA',
                'EN_PROCESO',
                'FINALIZADA',
                'CANCELADA'
            )
        )
);
