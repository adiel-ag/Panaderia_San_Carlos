CREATE TABLE PRODUCCION_DETALLE (
    id_produccion_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_produccion NUMBER NOT NULL,
    id_producto NUMBER NOT NULL,
    id_receta NUMBER NOT NULL,
    cantidad_planificada NUMBER(12,3) NOT NULL,
    cantidad_producida NUMBER(12,3) DEFAULT 0 NOT NULL,

    CONSTRAINT pk_produccion_detalle
        PRIMARY KEY (id_produccion_detalle),

    CONSTRAINT fk_prod_det_produccion
        FOREIGN KEY (id_produccion)
        REFERENCES PRODUCCION(id_produccion),

    CONSTRAINT fk_prod_det_producto
        FOREIGN KEY (id_producto)
        REFERENCES PRODUCTO(id_producto),

    CONSTRAINT fk_prod_det_receta
        FOREIGN KEY (id_receta)
        REFERENCES RECETA(id_receta),

    CONSTRAINT uq_prod_det_producto
        UNIQUE (id_produccion, id_producto),

    CONSTRAINT ck_prod_det_planificada
        CHECK (cantidad_planificada > 0),

    CONSTRAINT ck_prod_det_producida
        CHECK (cantidad_producida >= 0)
);
