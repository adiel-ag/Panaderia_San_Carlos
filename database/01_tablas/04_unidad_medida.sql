CREATE TABLE UNIDAD_MEDIDA (
    id_unidad NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(50) NOT NULL,
    abreviatura VARCHAR2(10) NOT NULL,

    CONSTRAINT pk_unidad_medida
        PRIMARY KEY (id_unidad),

    CONSTRAINT uq_unidad_abreviatura
        UNIQUE (abreviatura)
);

