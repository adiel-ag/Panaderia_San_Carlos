CREATE TABLE RECETA_DETALLE (
    id_receta_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_receta NUMBER NOT NULL,
    id_insumo NUMBER NOT NULL,
    cantidad NUMBER(12,3) NOT NULL,

    CONSTRAINT pk_receta_detalle
        PRIMARY KEY (id_receta_detalle),

    CONSTRAINT fk_receta_det_receta
        FOREIGN KEY (id_receta)
        REFERENCES RECETA(id_receta),

    CONSTRAINT fk_receta_det_insumo
        FOREIGN KEY (id_insumo)
        REFERENCES PRODUCTO(id_producto),

    CONSTRAINT uq_receta_det_insumo
        UNIQUE (id_receta, id_insumo),

    CONSTRAINT ck_receta_det_cantidad
        CHECK (cantidad > 0)
);
