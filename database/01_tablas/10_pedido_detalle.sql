CREATE TABLE PEDIDO_DETALLE (
    id_pedido_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pedido NUMBER NOT NULL,
    id_producto NUMBER NOT NULL,
    cantidad NUMBER(12,3) NOT NULL,

    CONSTRAINT pk_pedido_detalle
        PRIMARY KEY (id_pedido_detalle),

    CONSTRAINT fk_pedido_det_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES PEDIDO(id_pedido),

    CONSTRAINT fk_pedido_det_producto
        FOREIGN KEY (id_producto)
        REFERENCES PRODUCTO(id_producto),

    CONSTRAINT uq_pedido_det_producto
        UNIQUE (id_pedido, id_producto),

    CONSTRAINT ck_pedido_det_cantidad
        CHECK (cantidad > 0)
);
