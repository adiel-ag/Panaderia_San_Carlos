CREATE TABLE TIPO_PRODUCTO (
    id_tipo_producto NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(30) NOT NULL,

    CONSTRAINT pk_tipo_producto
        PRIMARY KEY (id_tipo_producto),

    CONSTRAINT uq_tipo_producto_nombre
        UNIQUE (nombre)
);
