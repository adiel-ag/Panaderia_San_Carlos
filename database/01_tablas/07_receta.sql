CREATE TABLE RECETA (
    id_receta NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_producto NUMBER NOT NULL,
    version NUMBER(5) DEFAULT 1 NOT NULL,
    rendimiento NUMBER(12,3) NOT NULL,
    estado VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL,
    fecha_inicio DATE DEFAULT SYSDATE NOT NULL,
    fecha_fin DATE,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_receta
        PRIMARY KEY (id_receta),

    CONSTRAINT fk_receta_producto
        FOREIGN KEY (id_producto)
        REFERENCES PRODUCTO(id_producto),

    CONSTRAINT uq_receta_producto_version
        UNIQUE (id_producto, version),

    CONSTRAINT ck_receta_version
        CHECK (version > 0),

    CONSTRAINT ck_receta_rendimiento
        CHECK (rendimiento > 0),

    CONSTRAINT ck_receta_estado
        CHECK (estado IN ('ACTIVA', 'INACTIVA'))
);
