-- Ejecutar DESPUES de copiar los datos desde la base local.
--   1. Vuelve a activar y validar las llaves foraneas (falla si algun dato
--      quedo sin su registro relacionado).
--   2. Ajusta cada contador de ID para que continue despues del ID mas alto
--      copiado; sin esto, el primer pedido nuevo chocaria con uno existente.
--   3. Muestra cuantas filas tiene cada tabla, para comparar con la base local.
-- Solo toca las 17 tablas de la panaderia; otros objetos del esquema no cambian.
SET SERVEROUTPUT ON
@@solo_nube.sql

DECLARE
    v_filas NUMBER;
    CURSOR c_tablas IS
        SELECT t.table_name
          FROM user_tables t
         WHERE t.table_name IN ('ROL', 'SUCURSAL', 'TIPO_PRODUCTO', 'UNIDAD_MEDIDA',
               'USUARIO', 'PRODUCTO', 'RECETA', 'RECETA_DETALLE', 'PEDIDO',
               'PEDIDO_DETALLE', 'PRODUCCION', 'PRODUCCION_PEDIDO', 'PRODUCCION_DETALLE',
               'INVENTARIO', 'MOVIMIENTO_INVENTARIO', 'DESPACHO', 'USUARIO_CREDENCIAL')
         ORDER BY t.table_name;
BEGIN
    FOR t IN c_tablas LOOP
        FOR c IN (SELECT constraint_name FROM user_constraints
                   WHERE table_name = t.table_name AND constraint_type = 'R'
                     AND status = 'DISABLED') LOOP
            EXECUTE IMMEDIATE 'ALTER TABLE "' || t.table_name || '" ENABLE VALIDATE CONSTRAINT "'
                              || c.constraint_name || '"';
        END LOOP;
        FOR i IN (SELECT column_name FROM user_tab_identity_cols
                   WHERE table_name = t.table_name) LOOP
            EXECUTE IMMEDIATE 'ALTER TABLE "' || t.table_name || '" MODIFY "' || i.column_name
                              || '" GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)';
        END LOOP;
    END LOOP;

    FOR t IN c_tablas LOOP
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM "' || t.table_name || '"' INTO v_filas;
        DBMS_OUTPUT.PUT_LINE(RPAD(t.table_name, 25) || v_filas);
    END LOOP;
END;
/
