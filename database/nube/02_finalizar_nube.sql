-- Ejecutar DESPUES de copiar los datos desde la base local.
--   1. Vuelve a activar y validar las llaves foraneas (falla si algun dato
--      quedo sin su registro relacionado).
--   2. Ajusta cada contador de ID para que continue despues del ID mas alto
--      copiado; sin esto, el primer pedido nuevo chocaria con uno existente.
--   3. Muestra cuantas filas tiene cada tabla, para comparar con la base local.
SET SERVEROUTPUT ON
@@solo_nube.sql

BEGIN
    FOR c IN (SELECT table_name, constraint_name FROM user_constraints
               WHERE constraint_type = 'R' AND status = 'DISABLED') LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE "' || c.table_name || '" ENABLE VALIDATE CONSTRAINT "'
                          || c.constraint_name || '"';
    END LOOP;

    FOR i IN (SELECT table_name, column_name FROM user_tab_identity_cols) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE "' || i.table_name || '" MODIFY "' || i.column_name
                          || '" GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)';
    END LOOP;
END;
/

DECLARE
    v_filas NUMBER;
BEGIN
    FOR t IN (SELECT table_name FROM user_tables ORDER BY table_name) LOOP
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM "' || t.table_name || '"' INTO v_filas;
        DBMS_OUTPUT.PUT_LINE(RPAD(t.table_name, 25) || v_filas);
    END LOOP;
END;
/
PROMPT === Listo: llaves activas y contadores de ID ajustados.
